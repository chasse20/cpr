-- Run in the destination PostgreSQL database as an administrator before starting CPR
-- Creates the cpr_app login without a password; set it separately with psql's \password cpr_app
-- Re-running preserves queue and worker data
-- Review prompts are configured in appsettings.json under CPR:Prompts
BEGIN;

CREATE SCHEMA IF NOT EXISTS cpr;

DO $cpr$
BEGIN
	IF NOT EXISTS ( SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'cpr_app' ) THEN
		CREATE ROLE cpr_app LOGIN;
	END IF;

	EXECUTE format( 'GRANT CONNECT ON DATABASE %I TO cpr_app', current_database() );
END;
$cpr$;

CREATE TABLE IF NOT EXISTS cpr."Worker"
(
	"WorkerId" int NOT NULL,
	"SshHost" varchar(100) NOT NULL,
	"Status" int NOT NULL,
	"LastSeenAt" timestamp with time zone NULL,
	CONSTRAINT "PK_Worker" PRIMARY KEY ( "WorkerId" )
);

CREATE TABLE IF NOT EXISTS cpr."PullRequest"
(
	"PullRequestId" bigint GENERATED BY DEFAULT AS IDENTITY,
	"Repository" varchar(255) NOT NULL,
	"Number" int NOT NULL,
	"TargetBranch" varchar(255) NOT NULL,
	"HeadRepository" varchar(255) NOT NULL,
	"HeadBranch" varchar(255) NOT NULL,
	"RemoteSha" varchar(64) NOT NULL,
	"Status" int NOT NULL,
	"WorkReason" int NOT NULL,
	"WorkerId" int NULL,
	"SessionId" varchar(128) NULL,
	"PreparedSha" varchar(64) NULL,
	"ApprovedSha" varchar(64) NULL,
	"PublishedSha" varchar(64) NULL,
	"LastError" varchar(4096) NULL,
	"CreatedAt" timestamp with time zone NOT NULL,
	CONSTRAINT "PK_PullRequest" PRIMARY KEY ( "PullRequestId" ),
	CONSTRAINT "CK_PullRequest_Number" CHECK ( "Number" > 0 ),
	CONSTRAINT "FK_PullRequest_Worker_WorkerId" FOREIGN KEY ( "WorkerId" ) REFERENCES cpr."Worker" ( "WorkerId" ) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_PullRequest_Repository_Number" ON cpr."PullRequest" ( "Repository", "Number" );
CREATE INDEX IF NOT EXISTS "IX_PullRequest_Repository_TargetBranch_PullRequestId" ON cpr."PullRequest" ( "Repository", "TargetBranch", "PullRequestId" );
CREATE UNIQUE INDEX IF NOT EXISTS "IX_PullRequest_WorkerId" ON cpr."PullRequest" ( "WorkerId" );
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Worker_SshHost" ON cpr."Worker" ( "SshHost" );

-- Workspace ownership persists while no worker is actively assigned
ALTER TABLE cpr."PullRequest" ADD COLUMN IF NOT EXISTS "WorkspaceWorkerId" int NULL REFERENCES cpr."Worker" ( "WorkerId" ) ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS "IX_PullRequest_WorkspaceWorkerId" ON cpr."PullRequest" ( "WorkspaceWorkerId" );
UPDATE cpr."PullRequest" SET "WorkspaceWorkerId" = "WorkerId" WHERE "WorkspaceWorkerId" IS NULL AND "WorkerId" IS NOT NULL;

-- Retain terminal PR records independently of file cleanup
-- PullRequestStatus: Merged = 7, Closed = 8; existing status values are unchanged
ALTER TABLE cpr."PullRequest" ADD COLUMN IF NOT EXISTS "CompletedAt" timestamp with time zone NULL;
ALTER TABLE cpr."PullRequest" ADD COLUMN IF NOT EXISTS "CleanedAt" timestamp with time zone NULL;

-- Pin validation to its target and retain cleanup progress across restarts
-- PullRequestStatus: Blocked = 9, Removed = 10
ALTER TABLE cpr."PullRequest" ADD COLUMN IF NOT EXISTS "ReviewedTargetSha" varchar(64) NULL;
ALTER TABLE cpr."PullRequest" ADD COLUMN IF NOT EXISTS "CleanupRequestedAt" timestamp with time zone NULL;
UPDATE cpr."PullRequest" SET "CleanupRequestedAt" = COALESCE( "CompletedAt", now() ) WHERE "Status" IN ( 7, 8 ) AND "CleanupRequestedAt" IS NULL;

-- Retain explicit maintainer decisions for subsequent review and validation
ALTER TABLE cpr."PullRequest" ADD COLUMN IF NOT EXISTS "MaintainerResolution" varchar(16000) NULL;

-- Old records may have copies on workers whose assignments were already released
-- This one-time backfill is conservative; new records track only workers they use
ALTER TABLE cpr."PullRequest" ADD COLUMN IF NOT EXISTS "StorageWorkerIds" int[] NULL;
UPDATE cpr."PullRequest" SET "StorageWorkerIds" = CASE WHEN "CleanedAt" IS NULL THEN ARRAY( SELECT "WorkerId" FROM cpr."Worker" ORDER BY "WorkerId" ) ELSE '{}'::int[] END WHERE "StorageWorkerIds" IS NULL;
ALTER TABLE cpr."PullRequest" ALTER COLUMN "StorageWorkerIds" SET DEFAULT '{}'::int[];
ALTER TABLE cpr."PullRequest" ALTER COLUMN "StorageWorkerIds" SET NOT NULL;

CREATE TABLE IF NOT EXISTS cpr."ReviewRun"
(
	"ReviewRunId" bigint GENERATED BY DEFAULT AS IDENTITY,
	"PullRequestId" bigint NOT NULL REFERENCES cpr."PullRequest" ( "PullRequestId" ) ON DELETE RESTRICT,
	"WorkerId" int NOT NULL REFERENCES cpr."Worker" ( "WorkerId" ) ON DELETE RESTRICT,
	"RunKey" varchar(128) NOT NULL,
	"Details" jsonb NOT NULL,
	CONSTRAINT "PK_ReviewRun" PRIMARY KEY ( "ReviewRunId" )
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_ReviewRun_PullRequestId_WorkerId_RunKey" ON cpr."ReviewRun" ( "PullRequestId", "WorkerId", "RunKey" );
CREATE INDEX IF NOT EXISTS "IX_ReviewRun_WorkerId" ON cpr."ReviewRun" ( "WorkerId" );

-- Persist Discord status updates in the same transaction as the PR change
-- Delivered rows are deleted; disabled notifications do not enqueue new rows
CREATE TABLE IF NOT EXISTS cpr."DiscordNotification"
(
	"DiscordNotificationId" bigint GENERATED BY DEFAULT AS IDENTITY,
	"PullRequestId" bigint NOT NULL REFERENCES cpr."PullRequest" ( "PullRequestId" ) ON DELETE RESTRICT,
	"WebhookId" varchar(20) NOT NULL,
	"Status" int NOT NULL,
	"Detail" varchar(1000) NULL,
	"CreatedAt" timestamp with time zone NOT NULL,
	CONSTRAINT "PK_DiscordNotification" PRIMARY KEY ( "DiscordNotificationId" )
);
-- Upgrade the earlier DM layout if it was applied; old user IDs never match webhook IDs
DO $cpr$
BEGIN
	IF EXISTS ( SELECT 1 FROM information_schema.columns WHERE table_schema = 'cpr' AND table_name = 'DiscordNotification' AND column_name = 'UserId' ) THEN
		ALTER TABLE cpr."DiscordNotification" RENAME COLUMN "UserId" TO "WebhookId";
		ALTER INDEX IF EXISTS cpr."IX_DiscordNotification_UserId_DiscordNotificationId" RENAME TO "IX_DiscordNotification_WebhookId_DiscordNotificationId";
	END IF;
END;
$cpr$;
CREATE INDEX IF NOT EXISTS "IX_DiscordNotification_WebhookId_DiscordNotificationId" ON cpr."DiscordNotification" ( "WebhookId", "DiscordNotificationId" );
CREATE INDEX IF NOT EXISTS "IX_DiscordNotification_PullRequestId" ON cpr."DiscordNotification" ( "PullRequestId" );

-- WorkerStatus: Online = 0, Offline = 1, Paused = 2
INSERT INTO cpr."Worker" ( "WorkerId", "SshHost", "Status" )
VALUES
	( 101, 'cpr-101', 1 ),
	( 102, 'cpr-102', 1 ),
	( 103, 'cpr-103', 1 ),
	( 104, 'cpr-104', 1 ),
	( 105, 'cpr-105', 1 ),
	( 106, 'cpr-106', 1 ),
	( 107, 'cpr-107', 1 ),
	( 108, 'cpr-108', 1 ),
	( 109, 'cpr-109', 1 )
ON CONFLICT ( "WorkerId" ) DO NOTHING;

-- Runtime access; schema and table ownership stay with the administrator
GRANT USAGE ON SCHEMA cpr TO cpr_app;
GRANT SELECT, UPDATE ON TABLE cpr."Worker" TO cpr_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE cpr."PullRequest" TO cpr_app;
GRANT SELECT, INSERT, UPDATE ON TABLE cpr."ReviewRun" TO cpr_app;
GRANT SELECT, INSERT, DELETE ON TABLE cpr."DiscordNotification" TO cpr_app;

COMMIT;
